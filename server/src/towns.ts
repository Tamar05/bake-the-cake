// Exact-match lookup (case-sensitive — names come from the fixed list above, so
// a client-supplied value either matches exactly or it doesn't; free text goes
// through the separate 'Other: ' convention instead of a fuzzy match here).
export function findTown(name: string): Town | undefined {
  return BY_NAME.get(name);
}

function toRad(deg: number): number {
  return (deg * Math.PI) / 180;
}

// Great-circle distance in kilometers between two points (haversine formula).
export function distanceKm(a: { lat: number; lng: number }, b: { lat: number; lng: number }): number {
  const R = 6371;
  const dLat = toRad(b.lat - a.lat);
  const dLng = toRad(b.lng - a.lng);
  const h =
    Math.sin(dLat / 2) ** 2 +
    Math.cos(toRad(a.lat)) * Math.cos(toRad(b.lat)) * Math.sin(dLng / 2) ** 2;
  return 2 * R * Math.asin(Math.sqrt(h));
}

